import fs from 'node:fs';
import path from 'node:path';
import { claudeHomeDir, paths, type Config } from '../config.js';

export const HOOK_EVENTS = ['SessionStart', 'Stop', 'SessionEnd'] as const;
export const HOOK_MARKER = 'claude-board-hook';
export const HOOK_FILE = `${HOOK_MARKER}.mjs`;

/**
 * The script Claude Code runs on each hook. It never calls an LLM, never blocks Claude Code:
 * runner-started sessions are skipped, every network wait is capped, and it always exits 0.
 */
export function hookScript(port: number): string {
  return `#!/usr/bin/env node
// Claude Board hook. Generated by "claude-board hooks install"; "claude-board hooks uninstall" removes it.
const event = process.argv[2] || 'unknown';
const done = (out) => {
  if (out) process.stdout.write(out);
  process.exit(0);
};
// Sessions started by the Board itself (runner, classification) are already tracked.
if (process.env.CLAUDE_BOARD_EXECUTION_ID || process.env.CLAUDE_BOARD_INTERNAL) done();
const url = (process.env.CLAUDE_BOARD_URL || 'http://127.0.0.1:${port}') + '/api/hooks/' + event;
setTimeout(() => done(), 900).unref();
let input = '';
process.stdin.setEncoding('utf8');
process.stdin.on('data', (d) => (input += d));
process.stdin.on('end', async () => {
  try {
    const ctrl = new AbortController();
    setTimeout(() => ctrl.abort(), 700).unref();
    const res = await fetch(url, { method: 'POST', headers: { 'content-type': 'application/json' }, body: input || '{}', signal: ctrl.signal });
    if (event === 'SessionStart' && res.ok) {
      const body = await res.json();
      if (body && body.additionalContext) {
        done(JSON.stringify({ hookSpecificOutput: { hookEventName: 'SessionStart', additionalContext: body.additionalContext } }));
      }
    }
  } catch {
    // Board off or slow: stay silent.
  }
  done();
});
`;
}

export interface HooksStatus {
  installed: boolean;
  settingsPath: string;
  scriptPath: string;
  events: string[];
  cleanupPeriodDays: number | null;
}

type Settings = Record<string, any>;
type HookGroup = { matcher?: string; hooks: { type: string; command: string; timeout?: number }[] };

export function settingsPath(config: Config): string {
  return path.join(claudeHomeDir(config), 'settings.json');
}

function readSettings(file: string): Settings {
  if (!fs.existsSync(file)) return {};
  const raw = fs.readFileSync(file, 'utf8');
  if (!raw.trim()) return {};
  try {
    return JSON.parse(raw);
  } catch (err) {
    throw new Error(`Não mexi em ${file}: o JSON está inválido (${(err as Error).message}).`);
  }
}

function backupSettings(file: string): string | null {
  if (!fs.existsSync(file)) return null;
  const stamp = new Date().toISOString().replace(/[:.]/g, '-');
  const dest = path.join(paths.backups(), `settings-${stamp}.json`);
  fs.mkdirSync(paths.backups(), { recursive: true });
  fs.copyFileSync(file, dest);
  return dest;
}

function writeSettings(file: string, settings: Settings): void {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  const tmp = `${file}.claude-board.tmp`;
  fs.writeFileSync(tmp, JSON.stringify(settings, null, 2) + '\n');
  fs.renameSync(tmp, file);
}

const isOurs = (h: { command?: string }) => typeof h?.command === 'string' && h.command.includes(HOOK_MARKER);

export function hooksStatus(config: Config): HooksStatus {
  const file = settingsPath(config);
  let settings: Settings = {};
  try {
    settings = readSettings(file);
  } catch {
    settings = {};
  }
  const events = HOOK_EVENTS.filter((ev) =>
    (settings.hooks?.[ev] as HookGroup[] | undefined)?.some((g) => Array.isArray(g?.hooks) && g.hooks.some(isOurs)),
  );
  return {
    installed: events.length === HOOK_EVENTS.length,
    settingsPath: file,
    scriptPath: path.join(paths.hooks(), HOOK_FILE),
    events: [...events],
    cleanupPeriodDays: typeof settings.cleanupPeriodDays === 'number' ? settings.cleanupPeriodDays : null,
  };
}

/** Forward slashes work in both shells Claude Code may use for hooks on Windows (cmd and Git Bash). */
const slash = (p: string) => p.replace(/\\/g, '/');

export function installHooks(config: Config): { backup: string | null; status: HooksStatus } {
  const file = settingsPath(config);
  const settings = readSettings(file);
  const script = path.join(paths.hooks(), HOOK_FILE);
  fs.mkdirSync(paths.hooks(), { recursive: true });
  fs.writeFileSync(script, hookScript(config.port));

  const backup = backupSettings(file);
  settings.hooks = settings.hooks && typeof settings.hooks === 'object' ? settings.hooks : {};
  for (const ev of HOOK_EVENTS) {
    const groups: HookGroup[] = Array.isArray(settings.hooks[ev]) ? settings.hooks[ev] : [];
    // Replace an older copy of our hook instead of adding a second one.
    const cleaned = groups
      .map((g) => ({ ...g, hooks: (g.hooks ?? []).filter((h) => !isOurs(h)) }))
      .filter((g) => g.hooks.length > 0);
    cleaned.push({ hooks: [{ type: 'command', command: `"${slash(process.execPath)}" "${slash(script)}" ${ev}`, timeout: 5 }] });
    settings.hooks[ev] = cleaned;
  }
  writeSettings(file, settings);
  return { backup, status: hooksStatus(config) };
}

export function uninstallHooks(config: Config): { backup: string | null; status: HooksStatus } {
  const file = settingsPath(config);
  const settings = readSettings(file);
  if (!settings.hooks) return { backup: null, status: hooksStatus(config) };
  const backup = backupSettings(file);
  for (const ev of Object.keys(settings.hooks)) {
    const groups: HookGroup[] = Array.isArray(settings.hooks[ev]) ? settings.hooks[ev] : [];
    const cleaned = groups
      .map((g) => ({ ...g, hooks: (g.hooks ?? []).filter((h) => !isOurs(h)) }))
      .filter((g) => g.hooks.length > 0);
    if (cleaned.length) settings.hooks[ev] = cleaned;
    else delete settings.hooks[ev];
  }
  if (!Object.keys(settings.hooks).length) delete settings.hooks;
  writeSettings(file, settings);
  return { backup, status: hooksStatus(config) };
}

/** First-run recommendation: keep transcripts longer than the 30-day default so the import has history. */
export function setCleanupPeriodDays(config: Config, days: number): { backup: string | null; days: number } {
  if (!Number.isInteger(days) || days < 1) throw new Error('Informe um número inteiro de dias.');
  const file = settingsPath(config);
  const settings = readSettings(file);
  const backup = backupSettings(file);
  settings.cleanupPeriodDays = days;
  writeSettings(file, settings);
  return { backup, days };
}
